/** Convenience grouping for the doc + page header. */
export function countByStatus(): Record<ParityStatus, number> {
  const out: Record<ParityStatus, number> = {
    present: 0,
    partial: 0,
    missing: 0,
    "admin-only": 0,
  };
  for (const r of PARITY_ROWS) out[r.status] += 1;
  return out;
}

/** Sorted unique resources for filter UI. */
export function uniqueResources(): Resource[] {
  return Array.from(new Set(PARITY_ROWS.map((r) => r.resource))).sort() as Resource[];
}
