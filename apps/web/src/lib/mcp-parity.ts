export type Priority = "high" | "medium" | "low";

export interface ParityRow {
  /** Logical resource (groups rows in the doc and matrix). */
  resource: Resource;
  /** What the user can do (UI-facing verb). */
  action: string;
  /** REST endpoint(s). Empty string if action exists only via MCP. */
  apiEndpoints: string[];
  /** MCP tool name, or null if no equivalent exists. */
  mcpTool: string | null;
  /** Coverage label. */
  status: ParityStatus;
  /** Free-text note explaining the gap (or "" if none). */
  note: string;
  /** Recommended priority for closing the gap (only meaningful when
   *  status !== "present"). */
  priority?: Priority;
}

