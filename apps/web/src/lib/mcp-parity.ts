/**
 * MCP ↔ REST API parity matrix.
 *
 * The Rokki product principle (CLAUDE.md, "Non-negotiables"): every
 * feature available in the UI is available via API and MCP tool. This
 * file is the source of truth for whether that holds today.
 *
 * Each row is a logical resource action ("create task", "list files in
 * a folder"). For each action we record:
 *   - the API endpoint(s) that satisfy it (path + method),
 *   - the MCP tool that satisfies it (or null),
 *   - a coverage label and gap note.
 *
 * Used by:
 *   - /admin/mcp page (renders this as a dense matrix)
 *   - docs/12_MCP_PARITY.md (regenerated by hand from the same data)
 *
 * When you add a new MCP tool, update this file. When you add a new
 * API endpoint, add a row here even if there's no MCP yet — that's the
 * whole point of the audit.
 */

export type ParityStatus =
  /** API and MCP both implement it (read OR write parity present). */
  | "present"
  /** Read tool exists, but corresponding write/mutation tool is missing
      (or vice versa). The matrix uses yellow for these. */
  | "partial"
  /** API exists, no MCP equivalent. The high-priority gaps. */
  | "missing"
  /** Admin/internal-only — intentionally not exposed via MCP. */
  | "admin-only";

export type Resource =
  | "auth"
  | "spaces"
  | "terminals"
  | "tasks"
  | "files"
  | "markets"
  | "folders"
